async function main() {
  const seedDataPath = path.join(process.cwd(), "lib", "admin", "seedData.js");
  let content = fs.readFileSync(seedDataPath, "utf-8");

  const startMarker = "// ==========================================\n// SEED DATA: INITIAL MENU ITEMS";
  const endMarker = "// ==========================================\n// SEED DATA: TABLES";

  const startIndex = content.indexOf(startMarker);
  const endIndex = content.indexOf(endMarker);

  if (startIndex === -1 || endIndex === -1) {
    console.error("Could not find markers in seedData.js!");
    process.exit(1);
  }

  const newSection = `// ==========================================
// SEED DATA: INITIAL MENU ITEMS (CAFE SPECIALS)
// ==========================================
export const INITIAL_MENU_ITEMS = ${JSON.stringify(CAFE_MENU_ITEMS, null, 2)};

export const INITIAL_CATEGORIES = ${JSON.stringify(CAFE_CATEGORIES, null, 2)};\n\n`;

  const updatedContent = content.slice(0, startIndex) + newSection + content.slice(endIndex);
  fs.writeFileSync(seedDataPath, updatedContent, "utf-8");
  console.log("Successfully updated lib/admin/seedData.js with new cafe menu items!");

  // Update data/admin-store.json if it exists
  const storePath = path.join(process.cwd(), "data", "admin-store.json");
  if (fs.existsSync(storePath)) {
    try {
      const storeData = JSON.parse(fs.readFileSync(storePath, "utf-8"));
      storeData.menuItems = CAFE_MENU_ITEMS;
      storeData.categories = CAFE_CATEGORIES;
      storeData.version = (storeData.version || 1) + 1;
      storeData.lastModified = new Date().toISOString();
      fs.writeFileSync(storePath, JSON.stringify(storeData, null, 2), "utf-8");
      console.log("Successfully updated data/admin-store.json with new cafe items!");
    } catch (err) {
      console.error("Failed to update admin-store.json:", err.message);
    }
  }
}

main();
